import 'fake-indexeddb/auto';
import { IDBFactory } from 'fake-indexeddb';
import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { WebSocket as NodeWebSocket } from 'ws';
import { loadConfig } from '../../../../server/src/config.js';
import { createLogger } from '../../../../server/src/logger.js';
import { startMockGnani } from '../../../../server/src/mock-gnani/index.js';
import { createGateway } from '../../../../server/src/server.js';
import { Vault } from '../storage/vault.js';
import { PhoneSession } from './controller.js';

it('dbg', async () => {
  const log: string[] = []; const t0 = Date.now(); const T = () => String(Date.now() - t0).padStart(5);
  const mock = await startMockGnani({ ttfbMs: 5, chunkIntervalMs: 15 });
  const config = { ...loadConfig({ MODE: 'local', GNANI_API_KEY: 'good', PORT: '0' }), gnaniBaseUrl: mock.url.replace('http', 'ws') };
  const gw = await createGateway({ config, log: createLogger(() => undefined, { strict: true }) });
  let timer: ReturnType<typeof setInterval> | null = null;
  const mic = { async open() {}, begin(sink: (f: ArrayBuffer) => void) { timer = setInterval(() => sink(new Int16Array(512).fill(3000).buffer), 32); }, end() { if (timer) clearInterval(timer); }, close() {} };
  const spk = { async open() {}, push() {}, flush() { log.push(T() + ' flush'); }, close() {}, onBusy: null };
  const vault = await Vault.open('x', new IDBFactory());
  const s = await PhoneSession.create({ gatewayUrl: gw.url.replace('http', 'ws') + '/ws', WebSocketImpl: NodeWebSocket as unknown as typeof WebSocket, vault, capture: mic, playback: spk as never, backoffMs: [50], onTelemetry: (t) => log.push(T() + ' tel ' + JSON.stringify(t)) });
  s.store.subscribe(() => log.push(`${T()} phase=${s.state.phase} online=${s.state.online} card=${s.state.card?.state}`));
  await new Promise((r) => setTimeout(r, 400));
  s.actions.finishOnboarding({ lang: 'hi', demoData: false });
  await new Promise((r) => setTimeout(r, 2500));
  log.push(T() + ' --- turn');
  mock.scriptTranscripts(['Mohan ka 50 udhaar']);
  s.actions.micDown();
  await new Promise((r) => setTimeout(r, 700));
  s.actions.micUp();
  await new Promise((r) => setTimeout(r, 3000));
  writeFileSync('/tmp/claude-1000/-home-caelum-projects-vidur/fa9b37b7-109e-4801-8670-3e0ea29dc21e/scratchpad/dbg3.out', log.join('\n'));
  s.dispose(); await gw.close(); await mock.close();
}, 30000);
