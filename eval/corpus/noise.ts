/**
 * Synthetic noise generators for the eval corpus. All noise is generated from a seed:
 * no audio files, no downloads, no third-party recordings.
 */

export const SAMPLE_RATE = 16000;

export const NOISE_LICENCES: Record<string, string> = {
  pink: 'synthetic, generated by eval/corpus/noise.ts, no third-party audio, no licence restrictions',
  brown: 'synthetic, generated by eval/corpus/noise.ts, no third-party audio, no licence restrictions',
  shopHum: 'synthetic, generated by eval/corpus/noise.ts, no third-party audio, no licence restrictions',
  babble: 'synthetic, generated by eval/corpus/noise.ts from corpus speech, no third-party audio, no licence restrictions',
};

export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function gaussian(rng: () => number): number {
  // Box–Muller
  let u = 0;
  let v = 0;
  while (u === 0) u = rng();
  v = rng();
  return Math.sqrt(-2.0 * Math.log(u)) * Math.cos(2.0 * Math.PI * v);
}

function floatToInt16(samples: Float64Array): Int16Array {
  const out = new Int16Array(samples.length);
  for (let i = 0; i < samples.length; i++) {
    const s = samples[i]!;
    out[i] = Math.max(-32768, Math.min(32767, Math.round(s * 32767)));
  }
  return out;
}

function secondsToLength(seconds: number): number {
  return Math.max(1, Math.floor(seconds * SAMPLE_RATE));
}

/** Paul Kellet's pink noise approximation. */
export function pink(seconds: number, seed: number): Int16Array {
  const rng = mulberry32(seed);
  const n = secondsToLength(seconds);
  const out = new Float64Array(n);
  let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
  for (let i = 0; i < n; i++) {
    const white = gaussian(rng);
    b0 = 0.99886 * b0 + white * 0.0555179;
    b1 = 0.99332 * b1 + white * 0.0750759;
    b2 = 0.969 * b2 + white * 0.153852;
    b3 = 0.8665 * b3 + white * 0.3104856;
    b4 = 0.55 * b4 + white * 0.5329522;
    b5 = -0.7616 * b5 - white * 0.016898;
    const pinkValue = b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362;
    b6 = white * 0.115926;
    out[i] = pinkValue * 0.11;
  }
  return floatToInt16(out);
}

/** Brown (red) noise: integrated white noise with a leak to prevent drift. */
export function brown(seconds: number, seed: number): Int16Array {
  const rng = mulberry32(seed);
  const n = secondsToLength(seconds);
  const out = new Float64Array(n);
  let last = 0;
  for (let i = 0; i < n; i++) {
    const white = gaussian(rng);
    last = (last + white * 0.02) * 0.998;
    out[i] = last * 3.5;
  }
  return floatToInt16(out);
}

/**
 * A shop rumble: 50 Hz mains hum plus harmonics, a band-limited noise floor,
 * and occasional short clicks/thumps (till drawer, shelf, dropped coin).
 */
export function shopHum(seconds: number, seed: number): Int16Array {
  const rng = mulberry32(seed);
  const n = secondsToLength(seconds);
  const out = new Float64Array(n);
  const brownNoise = brown(seconds, seed + 9999);

  let nextThump = Math.floor((0.2 + rng() * 0.8) * SAMPLE_RATE);
  let thumpRemaining = 0;
  let thumpAmplitude = 0;

  for (let i = 0; i < n; i++) {
    const t = i / SAMPLE_RATE;
    let sample =
      0.09 * Math.sin(2 * Math.PI * 50 * t) +
      0.035 * Math.sin(2 * Math.PI * 100 * t + 0.4) +
      0.018 * Math.sin(2 * Math.PI * 150 * t + 1.1) +
      0.009 * Math.sin(2 * Math.PI * 250 * t + 2.0) +
      (brownNoise[i]! / 32768) * 0.12;

    if (i >= nextThump) {
      thumpRemaining = Math.floor(SAMPLE_RATE * (0.01 + rng() * 0.03));
      thumpAmplitude = (0.5 + rng() * 0.5) * (rng() < 0.5 ? 1 : -1);
      nextThump = i + Math.floor((0.3 + rng() * 1.7) * SAMPLE_RATE);
    }
    if (thumpRemaining > 0) {
      const decay = Math.exp(-(thumpRemaining / (SAMPLE_RATE * 0.02)));
      sample += thumpAmplitude * decay * (rng() < 0.85 ? 1 : gaussian(rng));
      thumpRemaining -= 1;
    }
    out[i] = sample;
  }
  return floatToInt16(out);
}

/**
 * Crowd babble: 5–6 randomly time-shifted, gain-varied copies of the given speech
 * clips, summed. Clips are looped as needed to fill `seconds`.
 */
export function babble(clips: Int16Array[], seconds: number, seed: number): Int16Array {
  const rng = mulberry32(seed);
  const n = secondsToLength(seconds);
  const out = new Float64Array(n);
  const voices = 5 + Math.floor(rng() * 2); // 5 or 6
  const usable = clips.filter((c) => c.length > 0);

  for (let v = 0; v < voices; v++) {
    const clip = usable.length > 0 ? usable[Math.floor(rng() * usable.length)]! : null;
    if (!clip) break;
    const gain = 0.35 + rng() * 0.65;
    let offset = Math.floor(rng() * n);
    while (offset < n) {
      for (let i = 0; i < clip.length && offset + i < n; i++) {
        out[offset + i] += (clip[i]! / 32768) * gain;
      }
      // small random gap between repetitions of this voice
      offset += clip.length + Math.floor((0.05 + rng() * 0.4) * SAMPLE_RATE);
    }
  }

  // Peak-normalize to avoid clipping; relative levels are what matter here.
  let peak = 0;
  for (let i = 0; i < n; i++) peak = Math.max(peak, Math.abs(out[i]!));
  if (peak > 0.95) {
    const scale = 0.95 / peak;
    for (let i = 0; i < n; i++) out[i] *= scale;
  }
  return floatToInt16(out);
}

