export const TEMPLATES: Record<SpeechLang, Table> = { en, hi, kn };

/** The text for `key` in `lang`. Unknown placeholders are left out, never invented. */
export function say(lang: SpeechLang, key: Key, params: P = {}): string {
  return TEMPLATES[lang][key](params);
}

/** A marker that must appear in the disclosure of each language, so a test can prove the AI is named. */
